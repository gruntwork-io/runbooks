/**
 * SQL query execution for the <SQLite> block.
 *
 * Speaks only to the SqlDatabase interface (src/domain/session/store.ts), so
 * this module imports no Node API — src/layers/NodeSqlite.ts opens the actual
 * database. A statement that returns columns (SELECT, PRAGMA, ...) is run
 * with `all()` and yields a result set; anything else runs with `run()` and
 * yields the affected-row count.
 */

import { Effect } from "effect"
import { SqliteQueryError } from "../../errors/index.ts"
import type { SqlDatabase, SqlValue } from "../session/store.ts"
import type { SqlParam, SqlQueryResult } from "./result.ts"

/** Convert a block param to a value node:sqlite can bind. */
function toSqlValue(p: SqlParam): SqlValue {
  if (p === null) return null
  if (typeof p === "boolean") return p ? 1 : 0
  return p
}

/**
 * Run `sql` with `params` against `db`. Returns a SqlQueryResult: for
 * read queries, the column names and every row; for writes, the affected
 * row count. Errors are wrapped in SqliteQueryError.
 */
export function runQuery(db: SqlDatabase, sql: string, params: SqlParam[] = []) {
  return Effect.gen(function* () {
    if (!sql.trim()) {
      return yield* new SqliteQueryError({ message: "SQL query is empty" })
    }
    const values = params.map(toSqlValue)
    try {
      const stmt = db.prepare(sql)
      const cols = stmt.columns()
      if (cols.length > 0) {
        // Positional rows when the runtime supports it (node:sqlite
        // setReturnArrays, Node 22.16+ / Electron's bundled Node): duplicate
        // column names (SELECT 1 AS a, 2 AS a) keep each value. Otherwise
        // all() returns objects keyed by name and duplicates collapse to the
        // last value; dedupe the displayed names so a generated alias (a_2)
        // can't collide with an existing one.
        const setReturnArrays = stmt.setReturnArrays
        const positional = typeof setReturnArrays === "function"
        if (positional) setReturnArrays.call(stmt, true)
        const rawRows = stmt.all(...values)
        const reserved = new Set(cols.map((c) => c.name))
        const seen = new Map<string, number>()
        const columns = cols.map((c) => {
          const n = seen.get(c.name) ?? 0
          seen.set(c.name, n + 1)
          if (n === 0) return c.name
          let candidate = `${c.name}_${n + 1}`
          while (reserved.has(candidate)) candidate = `${candidate}_`
          reserved.add(candidate)
          return candidate
        })
        const rows = positional
          ? (rawRows as unknown[][])
          : (rawRows as Record<string, unknown>[]).map((row) => cols.map((c) => row[c.name]))
        return {
          columns,
          rows,
          rowCount: rows.length,
          isRead: true,
        } satisfies SqlQueryResult
      }
      const info = stmt.run(...values)
      return {
        columns: [],
        rows: [],
        rowCount: Number(info.changes),
        isRead: false,
      } satisfies SqlQueryResult
    } catch (err) {
      return yield* new SqliteQueryError({
        message: err instanceof Error ? err.message : String(err),
        cause: err,
      })
    }
  })
}

/**
 * Execute a SQL script (possibly multiple statements, e.g. a .sql file
 * generated by a <Template> block) with `exec`. Returns no result set:
 * the block shows it as a write. Errors are wrapped in SqliteQueryError.
 */
export function runSqlScript(db: SqlDatabase, sql: string) {
  return Effect.gen(function* () {
    if (!sql.trim()) {
      return yield* new SqliteQueryError({ message: "SQL script is empty" })
    }
    try {
      db.exec(sql)
      return {
        columns: [],
        rows: [],
        rowCount: 0,
        isRead: false,
      } satisfies SqlQueryResult
    } catch (err) {
      return yield* new SqliteQueryError({
        message: err instanceof Error ? err.message : String(err),
        cause: err,
      })
    }
  })
}
